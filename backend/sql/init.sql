CREATE DATABASE IF NOT EXISTS tv_simulator
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tv_simulator;

-- ── Users ─────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    username   VARCHAR(50)  UNIQUE NOT NULL,
    password   VARCHAR(255) NOT NULL,            -- SHA-256 hashed
    role       VARCHAR(20)  DEFAULT 'user',      -- 'user' | 'admin'
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ── Sessions (token-based auth for cross-origin / Vercel frontend) ────────
CREATE TABLE IF NOT EXISTS sessions (
    token      VARCHAR(255) PRIMARY KEY,
    user_id    INT          NOT NULL,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP    NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ── Favorites (per-user channel favourites) ───────────────────────────────
CREATE TABLE IF NOT EXISTS favorites (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    user_id       INT NOT NULL,
    channel_number INT NOT NULL,
    added_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_user_channel (user_id, channel_number),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ── Visit history (tracks channel visits for recommendations) ──────────────
CREATE TABLE IF NOT EXISTS visit_history (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    user_id       INT,                               -- nullable for anonymous
    channel_number INT NOT NULL,
    visit_count   INT DEFAULT 1,
    last_visited  TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_user_channel (user_id, channel_number),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- ── Parental control (locked channels per user) ───────────────────────────
CREATE TABLE IF NOT EXISTS parental_control (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    user_id       INT NOT NULL,
    channel_number INT NOT NULL,
    is_locked     BOOLEAN DEFAULT TRUE,
    UNIQUE KEY uniq_user_channel (user_id, channel_number),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ── User settings (parental PIN, etc.) ────────────────────────────────────
CREATE TABLE IF NOT EXISTS user_settings (
    user_id           INT PRIMARY KEY,
    parental_pin      VARCHAR(255),                  -- SHA-256 hashed
    parental_enabled  BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ── Commercials (ads shown in the TV client) ───────────────────────────────
CREATE TABLE IF NOT EXISTS commercials (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    title            VARCHAR(100) NOT NULL,
    content          TEXT,
    image_url        VARCHAR(500),
    target_channel   INT,                            -- NULL = all channels
    duration_seconds INT DEFAULT 15,
    is_active        BOOLEAN DEFAULT TRUE,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

